from typing import Any, Dict, Optional
from pydantic import BaseModel, Field


class GatewayUsage(BaseModel):
    """Normalized token usage and cost accounting."""
    input_tokens: int = Field(default=0, ge=0, description="Tokens consumed by input prompt/context")
    output_tokens: int = Field(default=0, ge=0, description="Tokens generated in completion")
    total_tokens: int = Field(default=0, ge=0, description="Total tokens consumed")
    usage_source: str = Field(default="provider", description="Source of usage metrics ('provider' or 'estimated')")
    estimated_cost: Optional[float] = Field(default=None, description="Calculated USD cost based on official model pricing")


class GatewayResponse(BaseModel):
    """
    Normalized, provider-independent model response contract.
    Returned to all application consumers regardless of underlying provider.
    """
    request_id: str = Field(..., description="Unique gateway request tracking UUID")
    provider: str = Field(..., description="Provider that satisfied the request (e.g. 'openai', 'mock')")
    model: str = Field(..., description="Model that produced the completion")
    content: str = Field(..., description="Text content generated by the model")
    finish_reason: str = Field(default="stop", description="Reason model stopped generating ('stop', 'length', etc.)")
    usage: GatewayUsage = Field(default_factory=GatewayUsage, description="Normalized token usage and cost")
    latency_ms: float = Field(default=0.0, ge=0.0, description="Total round-trip latency in milliseconds")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Operational metadata and trace references")
